// ADM-1 · Feature catalogue (DEC-214, DEC-215; 02 Planning/HCC_Admin_Panel_Plan_v1.md §2.1, §3).
// Every module lists its sub-functions ('features'); each feature names the nav pages it owns, the command prefixes it gates and the
// features it requires. Pure data: no state, no React. The Owner / Tech admin switch a feature off in Master configuration ›
// Modules & features (setting key `feature.<module>.<feature>`, store kind 'feature' in streams/config.ts); off = pages hidden,
// commands refused with the MODULE_OFF reason, data kept. `core:true` features can never be switched off (DEC-215).
//
// The ten DEC-057 module switches (CFG_MODULES in streams/config.ts, keys `module.<id>`) stay as they are: a catalogue module may
// point at one through `switch`, and a feature is only on while its module switch is on.
//
// The server mirrors this file in 08 Production/src/Hcc.Domain/Configuration/FeatureCatalog.cs; the golden
// 08 Production/database/feature-catalogue.json is generated by `node tools/feature-catalogue.mjs --write` and a test on each side
// fails when it drifts.

import type {Permission} from './types';

export type FeatureDef={
  /** Short id inside the module (`reservations`); the full id is `<module>.<feature>`. */
  id:string;label:string;
  /** Never switchable (DEC-215). Still listed so the panel can show it greyed with the reason. */
  core?:boolean;
  /** Nav page ids this feature owns (hidden while off). A page belongs to at most one feature. */
  pages:string[];
  /** Command type prefixes refused while off (`BOOK` matches BOOK and BOOKING_COMPANY; use `except` to carve out). */
  prefixes:string[];except?:string[];
  /** Full ids of features this one needs; switching one of those off switches this one off as well (with a confirm in the UI). */
  requires?:string[];
  /** ADM-2: server permission-id prefixes of this sub-function (`PERM-RES-`); the role grid grants / removes ids by these. */
  permPrefixes:string[];
  note:string;
};
export type FeatureModule={
  id:string;label:string;
  /** The DEC-057 module switch this module follows (`module.<switch>`), if it has one. */
  switch?:string;
  /** ADM-2: prototype coarse permissions a role needs to reach this module's pages (`can()`); the role grid adds / removes these. */
  coarse:Permission[];
  features:FeatureDef[];
};

