export type FeatureRef={module:FeatureModule;feature:FeatureDef;id:string;key:string};
const ALL:FeatureRef[]=FEATURE_MODULES.flatMap(m=>m.features.map(f=>({module:m,feature:f,id:m.id+'.'+f.id,key:'feature.'+m.id+'.'+f.id})));
const BY_ID=new Map(ALL.map(r=>[r.id,r]));
/** Every feature, module order. */
export const featureAll=()=>ALL;
export const featureById=(id:string)=>BY_ID.get(id);
export const featureKey=(id:string)=>'feature.'+id;
export const featureIdOfKey=(key:string)=>key.startsWith('feature.')?key.slice('feature.'.length):undefined;
/** The feature that owns a nav page, if any. */
export const featureOfPage=(page:string)=>ALL.find(r=>r.feature.pages.includes(page));
/** The feature that gates a command type: longest matching prefix wins, `except` prefixes are skipped. */
export function featureOfCommand(type:string):FeatureRef|undefined{
  let best:FeatureRef|undefined,len=-1;
  for(const r of ALL){
    if((r.feature.except||[]).some(p=>type.startsWith(p)))continue;
    for(const p of r.feature.prefixes)if(type.startsWith(p)&&p.length>len){best=r;len=p.length;}
  }
  return best;
}
/** Features that list `id` in `requires` (direct dependants only; callers walk it). */
export const featureDependants=(id:string)=>ALL.filter(r=>(r.feature.requires||[]).includes(id));
/** `id` plus every feature that transitively requires it. */
export function featureClosure(id:string):string[]{
  const out:string[]=[];const walk=(x:string)=>{if(out.includes(x))return;out.push(x);for(const d of featureDependants(x))walk(d.id);};
  walk(id);return out;
}
/** Commands of a switched-off feature that still pass (DEC-214 §2.2: a walk-in for today is a check-in, not a reservation). */
export function featureExempt(id:string,cmd:{type:string;[k:string]:unknown},today:string):boolean{
  return id==='frontdesk.reservations'&&cmd.type==='BOOK'&&cmd.arrival===today;
}
