# -*- coding: utf-8 -*-
"""Collects the finished course into Builds/<date>/training-hcc/ (decks, narration, videos, role cards, trainer's guide, README, notes, coverage) with SHA256.txt,
and writes the generated part of README.md (chapter table with steps, slides and durations per language, totals, sizes).
usage: python finalize.py [--date 2026-11-08] [--no-copy]"""
import os, sys, json, shutil, hashlib, re
HERE = os.path.dirname(os.path.abspath(__file__))
date = sys.argv[sys.argv.index('--date') + 1] if '--date' in sys.argv else '2026-11-08'
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))  # E:\Projects\HCC\worktrees\training -> parent of 'worktrees'? resolved below
DEST = os.path.join('E:\\Projects\\HCC\\Builds', date, 'training-hcc')
def hm(sec): sec = int(round(sec)); return '%d:%02d:%02d' % (sec // 3600, sec % 3600 // 60, sec % 60)
def mb(p): return '%.1f MB' % (os.path.getsize(p) / 1e6)
rows = []; tot = {}
def course(dirname, name):
    d = os.path.join(HERE, dirname); steps = json.load(open(os.path.join(d, 'steps.json'), encoding='utf-8'))
    man = json.load(open(os.path.join(d, 'build', 'deck', 'slides.json')))['slides']
    dur = {}
    for lang in ('en', 'hi'):
        p = os.path.join(d, 'build', 'work', lang, 'durations.json'); dur[lang] = {int(k): v for k, v in json.load(open(p)).items()} if os.path.exists(p) else {}
    table = []
    for c in steps['chapters']:
        sl = [m for m in man if m['chapter'] == c['id'] and m['kind'] in ('chapter', 'step', 'recap')]
        table.append((c['id'], c['title'], c['user'], len(c['steps']), len(sl), sum(dur['en'].get(m['n'], 0) for m in sl), sum(dur['hi'].get(m['n'], 0) for m in sl)))
    return table, len(man), sum(dur['en'].values()), sum(dur['hi'].values())
web, web_slides, web_en, web_hi = course('hcc-web', 'HCC-Training'); ph, ph_slides, ph_en, ph_hi = course('hcc-phone', 'HCC-Training-Phone')
def md_table(t):
    L = ['| Ch | Title | Role | Steps | Slides | English | Hinglish |', '|---|---|---|---|---|---|---|']
    for i, ti, u, n, s, e, h in t: L.append('| %d | %s | %s | %d | %d | %s | %s |' % (i, ti, u, n, s, hm(e), hm(h)))
    return L
gen = ['<!-- GENERATED by finalize.py: do not edit between the markers -->', '## Spot-check (final report)', '',
       '**Desktop course** (`hcc-web`): %d steps in %d chapters, %d slides; English %s, Hinglish %s.' % (sum(r[3] for r in web), len(web), web_slides, hm(web_en), hm(web_hi)), ''] + md_table(web) + \
      ['', '**Phone course** (`hcc-phone`, mobile shell 412x915 in Chrome): %d steps in %d chapters, %d slides; English %s, Hinglish %s.' % (sum(r[3] for r in ph), len(ph), ph_slides, hm(ph_en), hm(ph_hi)), ''] + md_table(ph) + ['<!-- END GENERATED -->']
gen = [g for g in gen if g != '<!-- END GENERATED -->']
if os.path.isdir(DEST):
    files = ['## Deliverables with sizes (Builds/%s/training-hcc)' % date, '', '| File | Size |', '|---|---|']
    for dp, _, fs in sorted(os.walk(DEST)):
        for f in sorted(fs):
            if f in ('SHA256.txt',) or (os.path.basename(dp).startswith('chapters-') and False): continue
            p = os.path.join(dp, f); files.append('| `%s` | %s |' % (os.path.relpath(p, DEST).replace(os.sep, '/'), mb(p)))
    gen += [''] + files
gen.append('<!-- END GENERATED -->')
readme = open(os.path.join(HERE, 'README.md'), encoding='utf-8').read()
if '<!-- GENERATED' in readme: readme = re.sub(r'<!-- GENERATED.*?<!-- END GENERATED -->', '\n'.join(gen), readme, flags=re.S)
else: readme = readme.rstrip() + '\n\n' + '\n'.join(gen) + '\n'
open(os.path.join(HERE, 'README.md'), 'w', encoding='utf-8').write(readme)
print('\n'.join(gen[:6]))
if '--no-copy' in sys.argv: sys.exit(0)
os.makedirs(DEST, exist_ok=True)
def cp(src, dstrel):
    if not os.path.exists(src): print('MISSING', src); return
    dst = os.path.join(DEST, dstrel); os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy2(src, dst)
for dirname, tag, name in (('hcc-web', 'desktop', 'HCC-Training'), ('hcc-phone', 'phone', 'HCC-Training-Phone')):
    b = os.path.join(HERE, dirname, 'build')
    for f in (name + '.pptx', name + '-hi.pptx', name + '-notes.md', name + '-notes-hinglish.md', name + '.mp4', name + '-hi.mp4'): cp(os.path.join(b, f), os.path.join(tag, f))
    for lang in ('en', 'hi'):
        vd = os.path.join(b, 'video', lang)
        if os.path.isdir(vd):
            for f in sorted(os.listdir(vd)): cp(os.path.join(vd, f), os.path.join(tag, 'chapters-' + lang, f))
rc = os.path.join(HERE, 'role-cards', 'build')
for f in sorted(os.listdir(rc)): cp(os.path.join(rc, f), os.path.join('Role cards', f))
tg = os.path.join(HERE, 'trainers-guide', 'build')
for f in sorted(os.listdir(tg)): cp(os.path.join(tg, f), f)
for f in ('README.md', 'TRAINING_NOTES.md', 'coverage.md'): cp(os.path.join(HERE, f), f)
lines = []
for dp, _, fs in os.walk(DEST):
    for f in sorted(fs):
        if f == 'SHA256.txt': continue
        p = os.path.join(dp, f); h = hashlib.sha256(); fh = open(p, 'rb')
        for blk in iter(lambda: fh.read(1 << 20), b''): h.update(blk)
        lines.append('%s  %s' % (h.hexdigest(), os.path.relpath(p, DEST).replace('\\', '/')))
open(os.path.join(DEST, 'SHA256.txt'), 'w', encoding='utf-8').write('\n'.join(sorted(lines, key=lambda x: x.split('  ')[1])) + '\n')
print('copied', len(lines), 'files to', DEST)
